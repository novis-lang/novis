import { describe, expect, test } from "bun:test";
import { chapterSources } from "../proofs/chapters.ts";
import { renderChapter } from "../renderers/lang-chapters.ts";

const source = (id: string) => chapterSources().find((s) => s.id === id)!;

describe("a generated language chapter", () => {
  test("each feature is its source's heading, then its texts and its examples", () => {
    const text = renderChapter(source("enums"));
    expect(text).toStartWith("---\nid: enums\ntitle: Enums\n");
    expect(text).toContain("generated: GENERATED by bun nv render");
    const headings = text.split("\n").filter((l) => l.startsWith("# "));
    expect(headings.map((h) => h.slice(2))).toEqual(source("enums").features.map((f) => f.heading));
    expect(text).toContain("# Declaring an enum\n\nDeclares a new type whose values are a fixed set of named numbers.");
    expect(text).toContain("## Example 01: the steps of an order\n\n```nvs\n<?nvs\n");
  });

  test("an example's fence says how it ends, and its diagnostic names main.nvs", () => {
    const text = renderChapter(source("enums"));
    const at = text.indexOf("## Example 05: a case written with case");
    expect(text.slice(at)).toMatch(/^## Example 05[^\n]*\n\n```nvs error\n/);
    expect(text.slice(at, text.indexOf("## Example 06", at))).toContain("--> main.nvs:6:13");
    expect(renderChapter(source("errors"))).toContain("```nvs exit=1\n");
    expect(renderChapter(source("testing"))).toContain("```nvs test exit=1\n");
  });

  test("a feature's nvs.toml is written before each example, without another example's block", () => {
    const text = renderChapter(source("errors"));
    const one = text.indexOf("## Example 01: a call nobody allowed");
    const two = text.indexOf("## Example 02: a grant in nvs toml");
    const first = text.slice(one, two);
    expect(first).toContain('```toml file=nvs.toml\n# Example 01 may not read any file.');
    expect(first).not.toContain("Example 02 may read");
    const own = text.slice(two, text.indexOf("## Example 03", two));
    expect(own).toContain('```toml file=nvs.toml\n# Example 02 may read the files in the `data` folder.');
    expect(own).toContain('[[app]]\nentry = "main.nvs"\n');
  });
});
