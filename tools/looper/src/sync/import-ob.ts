// The `ob` format, overbuild's, read as `crates/looper-core/src/import/ob.rs` reads it:
// `data/goal-order.json`, and per goal a numbered record `data/goals/NNNN.json` and handoff
// `data/handoffs/NNNN.json`, with pages generated from them into `docs/goals/`. The mapping is
// `docs/upgrade-guide.md` § *Mapping notes per project*.
//
// - **The chain** is `order`, each number turned into a slug: the record's title in lower case, every
//   run of other characters a `-`. A slug two titles share gets its goal's number after it. A note
//   names every number's slug.
// - **A goal's front matter** is the record's title, summary and stages, each stage's status as it is.
// - **A check** keeps its id, name and cwd, and the stage it is listed under. A `test` check runs
//   `bun ob test` on its atoms. A `command` check keeps its `run` and `inputs`, and its `contains`
//   becomes `stdout_contains`.
// - **The prose:** `why` goes under `## Why` and `decisions` under `## Standing decisions`, a bullet
//   each. Each stage becomes `### <id>. <title>` under `## Stages`, its `does` as `**Does:**` and its
//   `details` as bullets.
// - **The handoff** becomes `## Handoff`: `state` under `### State`, each `next` step an open item
//   under `### Next`, and each note a bullet under `### Backlog`. An item without a `path:line` anchor
//   gets its goal file as one.
// - **The generated pages** are the import's `generated`: each `docs/goals/*.md` whose first line says
//   `bun ob render` wrote it.
//
// Known gaps:
//
// - A `contains` line was found in stdout and stderr together, and `stdout_contains` reads stdout only,
//   so a check whose tool prints the line to stderr goes red.
// - A goal named by its number in the imported text keeps the number. `lint` reports each one.

import { readdirSync } from "node:fs";
import { join } from "node:path";
import { type Check, emptyCheck, FORMAT, type Goal, Refused, type Stage } from "../goal/model.ts";
import { list, str, strings, table, u32 } from "../goal/reader.ts";
import { anchors } from "../goal/sections.ts";
import type { Import } from "./import.ts";
import { opt, readJson, readText } from "./import-sand.ts";

/** The first line of every page `bun ob render` writes starts with this. */
const GENERATED = "<!-- Generated by `bun ob render`";

const orderJson = table<{ order: number[]; next: number }>(
  "OrderJson",
  { order: list(u32), next: u32 },
  () => ({ order: [], next: 0 }),
  ["order", "next"],
);

/** An ob check, its keys as the JSON spells them. */
export interface CheckJson {
  id: string;
  name: string;
  kind: string;
  tests?: string[];
  run?: string[];
  cwd?: string;
  inputs?: string[];
  contains?: string[];
}

export const checkJson = table<CheckJson>(
  "CheckJson",
  {
    id: str,
    name: str,
    kind: str,
    tests: opt(strings),
    run: opt(strings),
    cwd: opt(str),
    inputs: opt(strings),
    contains: opt(strings),
  },
  () => ({ id: "", name: "", kind: "" }),
  ["id", "name", "kind"],
);

interface StageJson {
  id: number;
  title: string;
  does: string;
  details: string[];
  status: string;
  checks: CheckJson[];
}

const stageJson = table<StageJson>(
  "StageJson",
  { id: u32, title: str, does: str, details: strings, status: str, checks: list(checkJson) },
  () => ({ id: 0, title: "", does: "", details: [], status: "", checks: [] }),
  ["id", "title", "does", "details", "status", "checks"],
);

interface GoalJson {
  title: string;
  summary: string;
  why: string[];
  decisions: string[];
  stages: StageJson[];
}

const goalJson = table<GoalJson>(
  "GoalJson",
  { title: str, summary: str, why: strings, decisions: strings, stages: list(stageJson) },
  () => ({ title: "", summary: "", why: [], decisions: [], stages: [] }),
  ["title", "summary", "why", "decisions", "stages"],
);

interface HandoffJson {
  state: string[];
  next: string[];
  notes: string[];
}

const handoffJson = table<HandoffJson>(
  "HandoffJson",
  { state: strings, next: strings, notes: strings },
  () => ({ state: [], next: [], notes: [] }),
  ["state", "next", "notes"],
);

/** Reads the ob project at `root`. */
export function readOb(root: string): Import {
  const order = readJson(root, "data/goal-order.json", orderJson);
  if (order === undefined) throw new Refused("data/goal-order.json is missing, so this is not an ob project");
  const notes: string[] = [];
  const goals: Goal[] = [];
  for (const n of order.order) {
    const num = String(n).padStart(4, "0");
    const path = `data/goals/${num}.json`;
    const g = readJson(root, path, goalJson);
    if (g === undefined) throw new Refused(`the order names ${n}, and ${path} is missing`);
    let slug = slugOf(g.title);
    if (goals.some((o) => o.slug === slug)) slug = `${slug}-${n}`;
    notes.push(`${path} is now goal ${slug}`);
    const handoff = readJson(root, `data/handoffs/${num}.json`, handoffJson);
    goals.push(goal(slug, g, handoff, notes));
  }
  return {
    chain: { looper: FORMAT, chain: goals.map((g) => g.slug), floor: [] },
    goals,
    playbook: undefined,
    bullet_files: [],
    notes,
    generated: generatedPages(root),
  };
}

/** The title in lower case, every run of characters that are not ASCII letters or digits one `-`. */
export function slugOf(title: string): string {
  let slug = "";
  for (const c of title) {
    if (/^[A-Za-z0-9]$/.test(c)) slug += c.toLowerCase();
    else if (slug !== "" && !slug.endsWith("-")) slug += "-";
  }
  return slug.replace(/-+$/, "");
}

/** Every page in `docs/goals/` that `bun ob render` wrote, sorted. */
function generatedPages(root: string): string[] {
  let names: string[];
  try {
    names = readdirSync(join(root, "docs/goals"));
  } catch {
    return [];
  }
  return names
    .filter((name) => name.endsWith(".md") && name !== ".md")
    .map((name) => `docs/goals/${name}`)
    .filter((rel) => readText(root, rel)?.startsWith(GENERATED) === true)
    .sort();
}

function goal(slug: string, g: GoalJson, handoff: HandoffJson | undefined, notes: string[]): Goal {
  const owner = `goal ${slug}`;
  let stagesText = "";
  const stages: Stage[] = [];
  const checks: Check[] = [];
  for (const st of g.stages) {
    stagesText += `### ${st.id}. ${st.title}\n\n**Does:** ${st.does.trim()}\n\n`;
    if (st.details.length > 0) stagesText += `${bullets(st.details)}\n\n`;
    stages.push({ id: st.id, title: st.title, status: st.status === "done" ? "done" : "open", context: undefined, extra: undefined });
    checks.push(...st.checks.map((c) => obCheck(c, st.id, owner, notes)));
  }
  const why = g.why.map((p) => p.trim()).join("\n\n");
  const handoffBody =
    handoff === undefined
      ? handoffText("", undefined, [], [], "", owner, notes)
      : handoffText(handoff.state.join("\n\n"), undefined, handoff.next, handoff.notes, `docs/goals/${slug}.md`, owner, notes);
  const body =
    `\n# ${g.title}\n\n## Why\n\n${why}\n\n## Standing decisions\n\n${bullets(g.decisions)}\n\n` +
    `## Stages\n\n${stagesText}## Handoff\n\n${handoffBody}`;
  return {
    slug,
    front: {
      looper: FORMAT,
      title: g.title,
      summary: g.summary,
      context: [],
      stages,
      checks,
      settings: undefined,
      extra: undefined,
    },
    body: `${body.trimEnd()}\n`,
    body_line: 1,
  };
}

/** One `- ` bullet per text, a text's own line breaks indented under it. */
export function bullets(texts: string[]): string {
  return texts.map((t) => `- ${t.trim().replaceAll("\n", "\n  ")}`).join("\n");
}

/** One ob check, listed under stage `stage`, as a looper check. */
export function obCheck(c: CheckJson, stage: number, owner: string, notes: string[]): Check {
  const out: Check = { ...emptyCheck(), id: c.id, stage, name: c.name, cwd: c.cwd };
  if (c.kind === "test") {
    out.run = ["bun", "ob", "test", ...(c.tests ?? [])];
  } else {
    out.run = c.run ?? [];
    out.inputs = c.inputs;
    if (c.contains !== undefined) {
      notes.push(`${owner}: check ${c.id} wants its \`contains\` lines on stdout; ob read stdout and stderr together`);
    }
    out.stdout_contains = c.contains;
  }
  return out;
}

/**
 * The `## Handoff` section's text: `state` under `### State`, `lead` and one open item per `next` under
 * `### Next`, and one bullet per `backlog` under `### Backlog`. An item without a `path:line` anchor
 * gets `fallback` as one, and a note for `owner` counts them.
 */
export function handoffText(
  state: string,
  lead: string | undefined,
  next: string[],
  backlog: string[],
  fallback: string,
  owner: string,
  notes: string[],
): string {
  let items = lead === undefined ? "" : `${lead}\n\n`;
  let anchored = 0;
  for (const raw of next) {
    let text = raw.trim().replaceAll("\n", "\n  ");
    if (anchors(text.split("\n")[0] ?? "").length === 0) {
      text += ` \`${fallback}:1\``;
      anchored++;
    }
    items += `- [ ] ${text}\n`;
  }
  if (anchored > 0) notes.push(`${owner}: ${anchored} handoff item(s) had no anchor and now point at \`${fallback}:1\``);
  let out = "";
  for (const [name, text] of [
    ["State", state.trim()],
    ["Next", items.trimEnd()],
    ["Backlog", bullets(backlog)],
  ] as const) {
    out += `### ${name}\n\n`;
    if (text !== "") out += `${text}\n\n`;
  }
  return `${out.trimEnd()}\n`;
}
