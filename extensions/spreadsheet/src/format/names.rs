//! The month and day names a date part shows: those of the read's `locale`, or of a section's
//! `[$-407]` prefix.
//!
//! Each row is CLDR's wide and abbreviated Gregorian month and day names in format context, for
//! English and for each language of `locale`'s separators table. They are copied from CLDR 49.0,
//! the release `icu_datetime` 2.4 bakes in, which `Novis\Intl` uses. [`of_tag`] finds a tag's row
//! by its language, as `locale::of_tag` finds separators. `no` reads the `nb` row, and a tag with
//! no row has English names.
//!
//! What it spends: the table, static data in the component of about 13 KiB.

